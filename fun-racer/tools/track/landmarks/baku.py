def pit_building():
    """The temporary pit building on Azadliq Square: about 270 m long, garages under a glazed
    hospitality floor and an open roof terrace under canopies (photographs of the 2016 to 2024
    races). The map has it as a 275 x 26 m "carport"; the model keeps that length and 17 m of
    the depth, the rest is the pit lane in front of it. Local x = 0 is the front (the garage
    doors), the building extends to -x; z runs from -135 to +135."""
    m = sg.SceneryMesh(-1.0e6, -1.0e6, 2.0e6)
    m.anchor(0.0, 0.0)
    length, depth = 270.0, 17.0
    white = (0.86, 0.86, 0.84, 1.0)
    # Ground floor: a dark band of open garages between white piers.
    sg.box(m, "concrete", (-depth, -0.5, -0.5 * length), (0.0, 0.25, 0.5 * length), (0.30, 0.30, 0.31, 0.0))
    bays = 36
    bay = length / bays
    for k in range(bays + 1):
        zc = -0.5 * length + k * bay
        sg.box(m, "concrete", (-depth, 0.0, zc - 0.35), (0.25, 4.6, zc + 0.35), WHITE)
    sg.box(m, "concrete", (-depth, 0.0, -0.5 * length), (-1.2, 4.6, 0.5 * length), DARK)
    sg.box(m, "concrete", (-depth, 4.6, -0.5 * length), (0.9, 5.4, 0.5 * length), WHITE)       # fascia / balcony
    # Hospitality floor: glass front, white ends and back.
    ring = np.array([[-depth, -0.5 * length], [0.0, -0.5 * length], [0.0, 0.5 * length], [-depth, 0.5 * length]])
    sg.prism(m, ring, [], 5.4, 9.6, "building_glass", "building_roof", (0.30, 0.42, 0.52, 1.0),
             (0.80, 0.80, 0.78, 0.0), 5.4)
    sg.box(m, "concrete", (-depth - 0.2, 9.6, -0.5 * length - 0.2), (0.9, 10.0, 0.5 * length + 0.2), WHITE)
    # Roof terrace: a row of white canopies on posts.
    for k in range(18):
        zc = -0.5 * length + (k + 0.5) * length / 18.0
        sg.box(m, "building_roof", (-depth + 2.0, 12.6, zc - 6.4), (-1.0, 12.9, zc + 6.4), (0.90, 0.90, 0.88, 0.0))
        for px in (-depth + 2.4, -1.4):
            for pz in (zc - 6.0, zc + 6.0):
                sg.box(m, "metal", (px - 0.1, 10.0, pz - 0.1), (px + 0.1, 12.6, pz + 0.1), STEEL)
    # Race control tower at the Turn 1 end.
    ring = np.array([[-depth, -0.5 * length - 14.0], [0.0, -0.5 * length - 14.0], [0.0, -0.5 * length - 0.4],
                     [-depth, -0.5 * length - 0.4]])
    sg.prism(m, ring, [], -0.5, 15.5, "building_glass", "building_roof", (0.30, 0.42, 0.52, 1.0),
             (0.80, 0.80, 0.78, 0.0), 0.0)
    # Pit wall: timing stands along the track edge of the pit lane (x = 11.6 to 13.6: 3 m and more from the road, behind the wall).
    for k in range(10):
        zc = -100.0 + k * 22.0
        sg.box(m, "metal", (12.9, 0.0, zc - 5.0), (13.2, 2.9, zc - 4.7), STEEL)
        sg.box(m, "metal", (12.9, 0.0, zc + 4.7), (13.2, 2.9, zc + 5.0), STEEL)
        sg.box(m, "building_roof", (11.6, 2.9, zc - 5.2), (13.6, 3.1, zc + 5.2), (0.82, 0.82, 0.80, 0.0))
    return m


