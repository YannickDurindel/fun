def stone_wall(mesh, lap, ref, height):
    """The fortress wall from its mapped outline: limestone, cut back behind the barrier, with
    merlons along the top. The round bastions are part of the outline."""
    f = lap.feature(ref)
    for ring in lap.corridor.cut(f.outers[0], 2.6):
        ring = sg.oriented(sg.clean_ring(ring), True)
        if len(ring) < 3:
            continue
        g = float(lap.ground.height(ring[:, 0], ring[:, 1]).min())
        mesh.anchor(*ring.mean(axis=0))
        sg.prism(mesh, ring, [], g - 1.5, g + height, "concrete", "concrete", SANDSTONE, SANDSTONE_DARK, g)
        # Merlons: a block every 2.4 m along the outline, set just inside it.
        for a, b in zip(ring, np.roll(ring, -1, axis=0)):
            length = float(np.hypot(*(b - a)))
            if length < 2.0:
                continue
            d = (b - a) / length
            inward = np.array([-d[1], d[0]])
            if not in_any(0.5 * (a + b) + inward * 0.4, [ring]):
                inward = -inward
            for k in range(int(length // 2.4)):
                p = a + d * (1.2 + 2.4 * k)
                oriented_box(mesh, "concrete", p + inward * 0.35, d, 0.6, 0.3, g + height, g + height + 0.9, SANDSTONE)


def maiden_tower(mesh, lap):
    """Qiz Qalasi: a limestone drum 29.5 m high and 16.5 m across with the long buttress on its
    seaward side; the mapped outline has both. Ribbed above the lower third, which the model
    shows as a darker upper band."""
    ring = sg.oriented(sg.clean_ring(lap.feature("way/299418016").outers[0]), True)
    g = float(lap.ground.height(ring[:, 0], ring[:, 1]).min())
    mesh.anchor(*ring.mean(axis=0))
    sg.prism(mesh, ring, [], g - 1.5, g + 10.0, "concrete", "concrete", SANDSTONE, SANDSTONE_DARK, g)
    sg.prism(mesh, ring, [], g + 10.0, g + 29.5, "concrete", "concrete", SANDSTONE_DARK, SANDSTONE_DARK, g)


def trackside(lap):
    rng = np.random.default_rng(20160619)     # the first race in Baku
    mesh = sg.SceneryMesh(0.0, 0.0, sg.CHUNK)
    c = lap.corridor
    stone_wall(mesh, lap, "way/1502989778", 9.5)
    stone_wall(mesh, lap, "way/1502989779", 9.5)
    maiden_tower(mesh, lap)

    # Where nothing may be planted: buildings, stands, the pit building and its lane.
    solid = [f.outers[0] for f in lap.buildings if float(c.nearest(f.outers[0])[2].min()) < 60.0]
    solid += [lap.band(s0 - 4.0, s1 + 4.0, side, d0 - 3.0, d0 + depth + 2.0) for _, s0, s1, side, d0, depth, _ in STANDS]
    solid.append(lap.band(5985.0, 310.0, -1, 0.0, 36.0))
    solid += [lap.band(s - 0.5 * width - 3.0, s + 0.5 * width + 3.0, side, d - 2.5, d + 4.0)
              for s, side, d, width in SCREENS]

    def blocked(p, clearance=2.2):
        if in_any(p, solid):
            return True
        return any(in_any(p + np.array(d) * clearance, solid) for d in ((1, 0), (-1, 0), (0, 1), (0, -1)))

    planted = []

    def plant(p, kind, height=None):
        idx, lat, dist = c.nearest(p[None])
        i = int(idx[0])
        if dist[0] < c.half[i] + 3.6 or blocked(p):
            return
        if any(np.hypot(*(p - q)) < 4.5 for q in planted[-60:]):
            return
        planted.append(p)
        # Beside the road the ground is the road's own verge; further out it is the terrain.
        near = dist[0] < c.half[i] + 18.0
        y = float(c.y[i]) - 0.1 if near else float(lap.ground.height(p[0], p[1]))
        if kind == "boulevard":
            kind = ["pine", "plane", "plane", "cypress", "palm"][int(rng.integers(5))]
        h = height or {"plane": rng.uniform(9.0, 13.0), "pine": rng.uniform(9.0, 14.0),
                       "cypress": rng.uniform(8.0, 12.0), "palm": rng.uniform(6.0, 9.0)}[kind]
        mesh.anchor(p[0], p[1])
        tree(mesh, p[0], y, p[1], float(h), kind, rng)

    # 1. The mapped trees and tree rows that stand on the 30 m verge, where the surroundings
    #    step plants nothing (it treats the verge as run-off).
    for f in lap.feats:
        pts = None
        if f.point is not None and f.tags.get("natural") == "tree":
            pts = f.point[None]
        elif f.line is not None and f.tags.get("natural") == "tree_row":
            pts, _ = su._resample(f.line, 8.0)
        if pts is None:
            continue
        for p in pts[c.keep_out(pts)]:
            plant(np.asarray(p, dtype=np.float64), "plane" if rng.uniform() < 0.75 else "pine")
    mapped = len(planted)
    # 2. The rows of the avenues.
    for s0, s1, side, d, spacing, kind in TREE_ROWS:
        for s in lap.stretch(s0, s1, spacing):
            p = lap.point(s + rng.uniform(-1.0, 1.0), side, d + rng.uniform(-0.4, 0.4))[[0, 2]]
            if c.keep_out(p[None])[0]:      # beyond the verge the baked trees take over
                plant(p, kind)

    # Advertising boards on the debris fence, 12 m panels.
    for s0, s1, side in BOARD_RUNS:
        for k, s in enumerate(lap.stretch(s0, s1, 12.4)[:-1]):
            i = lap.index(s + 6.0)
            p = lap.point(s + 6.0, side, 3.4)
            mesh.anchor(p[0], p[2])
            oriented_box(mesh, "building_roof", p[[0, 2]], c.tan[i], 5.9, 0.06, p[1] + 1.15, p[1] + 2.15,
                         BOARDS[(k + int(s0)) % len(BOARDS)])

    # Frames of the big screens (the screens themselves are in the recipe).
    for s, side, d, width in SCREENS:
        i = lap.index(s)
        for e in (-0.5, 0.5):
            p = lap.point(s + e * width, side, d + 0.9)
            mesh.anchor(p[0], p[2])
            oriented_box(mesh, "metal", p[[0, 2]], c.tan[i], 0.25, 0.25, p[1] - 0.3, p[1] + 11.0, STEEL)
    print(f"trackside: {mapped} mapped trees on the verge, {len(planted) - mapped} avenue trees")
    return mesh


