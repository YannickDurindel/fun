def write_models(lap):
    out = OUT / "landmarks"
    out.mkdir(exist_ok=True)
    entries = []

    def save(name, mesh):
        stats = sg.write_glb(out / f"{name}.glb", mesh, f"{ID}_{name}", "fun-racer tools/track/landmarks/baku.py")
        print(f"  {name}.glb: {stats['triangles']} triangles, {stats['bytes'] / 1024:.0f} kB")

    # The pit building: front 14 m from the left road edge (the pit lane), from the finish
    # line to the braking zone of Turn 1; its middle is at s = 150.
    save("pit_building", pit_building())
    i = lap.index(150.0)
    entries.append({"model": "pit_building", "at": {"s": 150.0, "side": -1, "dist": round(float(lap.corridor.half[i]) + 16.6, 2)}})
    # Start lights over the grid's start line (start_s of track.json).
    start = float(lap.track["start_s"])
    save("start_gantry", start_gantry(2.0 * float(lap.corridor.half[lap.index(start)]) + 7.0))
    entries.append({"model": "start_gantry", "at": {"s": round(start - 6.0, 1), "side": 1, "dist": 0.0}})
    mesh, origin = flame_towers(lap)
    save("flame_towers", mesh)
    entries.append({"model": "flame_towers", "at": {"xz": [round(float(origin[0]), 2), round(float(origin[1]), 2)]}})
    save("tv_tower", tv_tower())
    x, z = lap.proj.to_xz(TV_TOWER[0], TV_TOWER[1])
    entry = {"model": "tv_tower", "at": {"latlon": [TV_TOWER[0], TV_TOWER[1]]}}
    if not lap.ground.in_near(x, z):    # beyond the near terrain a landmark is placed at y = 0
        entry["y_offset"] = round(float(lap.ground.height(x, z)), 1)
    entries.append(entry)
    # Everything in world coordinates hangs on the origin; landmarks sit on the terrain, so
    # its height there is taken out again.
    save("trackside", trackside(lap))
    entries.append({"model": "trackside", "at": {"xz": [0.0, 0.0]},
                    "y_offset": round(-float(lap.ground.height(0.0, 0.0)), 3)})
    (OUT / "landmarks.json").write_text(json.dumps(entries, indent=1) + "\n")
    print(f"landmarks.json: {len(entries)} entries")


