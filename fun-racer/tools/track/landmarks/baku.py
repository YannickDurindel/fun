# ---- the track ---------------------------------------------------------------------------
class Lap:
    def __init__(self):
        self.track = json.loads((OUT / "track.json").read_text())
        self.profile = json.loads((OUT / "road_profile.json").read_text())
        self.terrain = json.loads((OUT / "terrain.json").read_text())
        self.proj = geom.Projection(self.track["origin_latlon"][0], self.track["origin_latlon"][1],
                                    float(self.terrain["plan_scale"]))
        self.ground = su.Ground(str(OUT))
        self.corridor = su.Corridor(self.track, {
            "width": self.profile["width"], "bank": self.profile["bank"],
            "verge_left": self.profile["verge_left"], "verge_right": self.profile["verge_right"]})
        c = self.corridor
        self.n, self.step, self.length = c.n, c.step, float(self.track["length"])
        cache = sorted((OUT / "raw").glob("surroundings_near_*.json"))
        if not cache:
            raise SystemExit("no surroundings cache in assets/tracks/baku/raw")
        self.feats, _ = su.load_features(cache[0].read_text(), self.proj)
        far = sorted((OUT / "raw").glob("surroundings_far_*.json"))
        self.far_feats = su.load_features(far[0].read_text(), self.proj)[0] if far else []
        self.buildings = [f for f in self.feats if f.outers and ("building" in f.tags or "building:part" in f.tags)]

    def index(self, s):
        return int(round((s % self.length) / self.step)) % self.n

    def point(self, s, side=0.0, from_edge=0.0):
        """(x, y, z) at lap distance s, `from_edge` metres beyond the road edge on `side`."""
        c, i = self.corridor, self.index(s)
        off = side * (c.half[i] + from_edge) if side else 0.0
        xz = c.xz[i] + c.right[i] * off
        return np.array([xz[0], c.y[i], xz[1]])

    def stretch(self, s0, s1, spacing):
        """Lap distances from s0 to s1 (may wrap) every `spacing` metres, both ends included."""
        span = (s1 - s0) % self.length
        k = max(1, int(round(span / spacing)))
        return [(s0 + span * j / k) % self.length for j in range(k + 1)]

    def band(self, s0, s1, side, d0, d1, spacing=24.0):
        """Ring (x, z) of the strip between d0 and d1 metres beyond the road edge."""
        ss = self.stretch(s0, s1, spacing)
        inner = [self.point(s, side, d0)[[0, 2]] for s in ss]
        outer = [self.point(s, side, d1)[[0, 2]] for s in ss]
        return su.simplify(np.array(inner + outer[::-1]), 0.3, closed=True)

    def latlon(self, ring):
        lat, lon = self.proj.to_latlon(np.asarray(ring)[:, 0], np.asarray(ring)[:, 1])
        return [[round(float(a), 6), round(float(b), 6)] for a, b in zip(lat, lon)]

    def feature(self, ref):
        for f in self.feats + self.far_feats:
            if f.ref == ref and f.outers:
                return f
        raise SystemExit(f"{ref} is not in the surroundings cache")


def in_any(pt, rings):
    return bool(rings) and bool(su.points_in_rings(np.asarray(pt, dtype=np.float64)[None], rings)[0])


# ---- the recipe block --------------------------------------------------------------------
def green_areas(lap, reach=400.0):
    """(kind, ring) of the mapped lawns and groves within `reach` of the lap, big ones first.

    The land-cover class "grass" is also what the map leaves blank, and in the middle of Baku
    blank means paving stones and dusty yards, so environment.json colours that class as
    ground. The real lawns are therefore painted again as "farmland" (coloured as watered
    lawn there) and the groves as "forest" on top of them, in the map's own order."""
    out = []
    for f in lap.feats:
        if not f.outers or "building" in f.tags or "building:part" in f.tags:
            continue
        c = su.land_class(f.tags)
        if c is None or c[0] not in (su.GRASS, su.FOREST):
            continue
        for ring in f.outers:
            if float(lap.corridor.nearest(ring)[2].min()) > reach:
                continue
            ring = su.simplify(ring, 1.5, closed=True)
            area = abs(sg.signed_area(ring))
            if len(ring) >= 3 and area >= 60.0:
                out.append((area, "farmland" if c[0] == su.GRASS else "forest", ring, f.ref))
    out.sort(key=lambda e: -e[0])
    return out


def recipe_block(lap):
    lines = [BEGIN, "[surroundings]\n",
             "# Groves of the boulevard and the gardens: planted, not woodland.\n",
             "tree_density = 90\n", 'tree_species = "broadleaved"\n', "\n"]
    for ref, why in EXCLUDE:
        lines += [f"[[surroundings.exclude]]    # {why}\n", f'osm = "{ref}"\n']
    lines.append("\n")
    for ref, height, why in HEIGHTS:
        note = f"    # {why}" if why else ""
        lines += ["[[surroundings.building]]\n", f'osm = "{ref}"\n', f"height = {height}{note}\n"]
    lines.append("\n# Lawns (farmland) and groves (forest) of the parks: see green_areas() in the generator.\n")
    for _, kind, ring, ref in green_areas(lap):
        lines += [f"[[surroundings.add]]    # {ref}\n", f'kind = "{kind}"\n',
                  f"polygon = {json.dumps(lap.latlon(ring))}\n"]
    lines.append("\n# Race-weekend grandstands (estimated footprints, see the generator).\n")
    for name, s0, s1, side, d0, depth, height in STANDS:
        ring = lap.band(s0, s1, side, d0, d0 + depth)
        lines += [f"[[surroundings.add]]    # {name}: s = {s0:.0f} to {s1:.0f}, {'right' if side > 0 else 'left'}\n",
                  'kind = "grandstand"\n', f"height = {height}\n", f"polygon = {json.dumps(lap.latlon(ring))}\n"]
    lines.append("\n# Big screens facing the stands.\n")
    for s, side, d, width in SCREENS:
        ring = lap.band(s - 0.5 * width, s + 0.5 * width, side, d, d + 0.5, spacing=width)
        lines += [f"[[surroundings.add]]    # s = {s:.0f}\n", 'kind = "screen"\n', "min_height = 4.5\n",
                  "height = 10.5\n", f"polygon = {json.dumps(lap.latlon(ring))}\n"]
    lines.append(END)
    return lines


def write_recipe(lap):
    text = RECIPE.read_text()
    if BEGIN in text:
        text = text[:text.index(BEGIN)] + text[text.index(END) + len(END):]
    text = text.rstrip("\n") + "\n\n" + "".join(recipe_block(lap))
    RECIPE.write_text(text)
    print(f"recipe: {len(HEIGHTS)} heights, {len(green_areas(lap))} green areas, {len(STANDS)} stands -> {RECIPE}")


# ---- mesh helpers ------------------------------------------------------------------------
def loft(mesh, material, rings, colour, cap_top=True, cap_bottom=False):
    """Faces between successive rings (each (k, 3), same k), flat shaded, facing outward."""
    rings = [np.asarray(r, dtype=np.float64) for r in rings]
    axis = np.array([r.mean(axis=0) for r in rings])
    for a, b, ca, cb in zip(rings[:-1], rings[1:], axis[:-1], axis[1:]):
        k = len(a)
        centre = 0.5 * (ca + cb)
        for j in range(k):
            quad = [a[j], a[(j + 1) % k], b[(j + 1) % k], b[j]]
            if np.linalg.norm(b[j] - b[(j + 1) % k]) < 1e-6:
                quad = quad[:3]
            mesh.face(material, quad, None, colour, float(rings[0][:, 1].min()), away_from=centre)
    if cap_top and np.ptp(rings[-1], axis=0).max() > 1e-6:
        mesh.face(material, rings[-1], (0.0, 1.0, 0.0), colour)
    if cap_bottom:
        mesh.face(material, rings[0], (0.0, -1.0, 0.0), colour)


def circle(cx, y, cz, rx, rz=None, sides=6, turn=0.0):
    rz = rx if rz is None else rz
    a = turn + np.arange(sides) * (2.0 * math.pi / sides)
    return np.stack([cx + rx * np.cos(a), np.full(sides, y), cz + rz * np.sin(a)], axis=1)


def oriented_box(mesh, material, centre, along, half_len, half_wid, y0, y1, colour):
    """Box with its long side along the plan direction `along` (unit (x, z))."""
    a = np.asarray(along, dtype=np.float64)
    r = np.array([-a[1], a[0]])
    c = np.asarray(centre, dtype=np.float64)
    corners = [c + a * sa * half_len + r * sr * half_wid for sa, sr in ((-1, -1), (1, -1), (1, 1), (-1, 1))]
    low = np.array([[p[0], y0, p[1]] for p in corners])
    high = np.array([[p[0], y1, p[1]] for p in corners])
    loft(mesh, material, [low, high], colour, cap_top=True, cap_bottom=True)


def tree(mesh, x, y, z, height, kind, rng):
    """One low-poly tree (15 to 35 triangles), drawn with the plain tinted roof material."""
    y -= 0.3
    turn = rng.uniform(0.0, math.pi)
    if kind == "cypress":
        loft(mesh, "building_roof", [circle(x, y, z, 0.18, sides=3), circle(x, y + 0.15 * height, z, 0.18, sides=3)],
             TRUNK, cap_top=False)
        r = 0.11 * height
        loft(mesh, "building_roof", [circle(x, y + 0.12 * height, z, 0.6 * r, sides=5, turn=turn),
                                     circle(x, y + 0.40 * height, z, r, sides=5, turn=turn),
                                     circle(x, y + height, z, 0.02, sides=5, turn=turn)],
             PINE[int(rng.integers(len(PINE)))], cap_top=False)
        return
    if kind == "palm":
        loft(mesh, "building_roof", [circle(x, y, z, 0.3, sides=3), circle(x, y + 0.82 * height, z, 0.22, sides=3)],
             TRUNK, cap_top=False)
        top = np.array([x, y + 0.86 * height, z])
        col = LEAF[int(rng.integers(len(LEAF)))]
        for j in range(5):
            a = turn + j * 2.0 * math.pi / 5.0
            d = np.array([math.cos(a), 0.0, math.sin(a)])
            w = np.array([-d[2], 0.0, d[0]]) * 0.55
            mid = top + d * 0.28 * height + np.array([0.0, 0.05 * height, 0.0])
            tip = top + d * 0.42 * height - np.array([0.0, 0.10 * height, 0.0])
            for quad in ([top - w * 0.3, top + w * 0.3, mid + w, mid - w], [mid - w, mid + w, tip]):
                mesh.face("building_roof", quad, (0.0, 1.0, 0.0), col)
                mesh.face("building_roof", quad[::-1], (0.0, -1.0, 0.0), col)
        return
    pine = kind == "pine"
    bole = (0.55 if pine else 0.36) * height
    loft(mesh, "building_roof", [circle(x, y, z, 0.26, sides=3), circle(x, y + bole + 0.1 * height, z, 0.18, sides=3)],
         TRUNK, cap_top=False)
    r = (0.30 if pine else 0.27) * height
    col = (PINE if pine else LEAF)[int(rng.integers(len(PINE if pine else LEAF)))]
    if pine:    # the umbrella crown of the Eldar pines of the boulevard
        levels = [(bole, 0.5), (bole + 0.35 * (height - bole), 1.0), (height, 0.25)]
    else:       # the round crown of a plane tree
        levels = [(bole, 0.4), (bole + 0.3 * (height - bole), 1.0), (bole + 0.72 * (height - bole), 0.85),
                  (height, 0.2)]
    rings = [circle(x + rng.uniform(-0.25, 0.25), y + h, z + rng.uniform(-0.25, 0.25), r * f, sides=5, turn=turn)
             for h, f in levels]
    loft(mesh, "building_roof", rings, col, cap_top=True, cap_bottom=True)


