# ----------------------------------------------------------------------------- the lap
class Lap:
    """track.json in plan view: lat / lon <-> metres <-> (s, lateral); lateral > 0 = right."""

    def __init__(self, folder=FOLDER):
        with open(folder / "track.json", encoding="utf-8") as f:
            t = json.load(f)
        with open(folder / "terrain.json", encoding="utf-8") as f:
            terrain = json.load(f)
        self.k = terrain["plan_scale"]
        near = terrain["near"]
        self.near_rect = (near["x0"], near["x0"] + (near["nx"] - 1) * near["step"],
                          near["z0"], near["z0"] + (near["nz"] - 1) * near["step"])
        self.lat0, self.lon0 = t["origin_latlon"]
        self.kx = EARTH * math.cos(math.radians(self.lat0))
        self.length = float(t["length"])
        self.start_s = float(t["start_s"])
        pts = np.array([p["p"] for p in t["points"]], dtype=float)
        self.xz, self.y = pts[:, [0, 2]], pts[:, 1]
        self.s = np.array([p["s"] for p in t["points"]], dtype=float)
        self.width = np.array([p["width"] for p in t["points"]], dtype=float)
        d = np.roll(self.xz, -1, axis=0) - np.roll(self.xz, 1, axis=0)
        self.tan = d / np.linalg.norm(d, axis=1)[:, None]
        self.right = np.stack([-self.tan[:, 1], self.tan[:, 0]], axis=1)
        self.turns = {u["id"]: float(u["s_apex"]) for u in t["turns"]}

    def to_xz(self, lat, lon):
        return (np.asarray(lon) - self.lon0) * self.kx * self.k, -(np.asarray(lat) - self.lat0) * EARTH * self.k

    def to_ll(self, x, z):
        return self.lat0 - (z / self.k) / EARTH, self.lon0 + (x / self.k) / self.kx

    def index(self, s):
        return int(round((s % self.length) / self.length * len(self.s))) % len(self.s)

    def at(self, s, lateral=0.0):
        i = self.index(s)
        return self.xz[i] + self.right[i] * lateral

    def half(self, s):
        return 0.5 * float(self.width[self.index(s)])

    def height(self, s):
        return float(self.y[self.index(s)])

    def locate(self, x, z):
        i = int(np.argmin(np.hypot(self.xz[:, 0] - x, self.xz[:, 1] - z)))
        v = np.array([x, z]) - self.xz[i]
        return float(self.s[i] + v @ self.tan[i]), float(v @ self.right[i])

    def distance(self, pts):
        pts = np.asarray(pts, dtype=float).reshape(-1, 2)
        out = np.empty(len(pts))
        for k, p in enumerate(pts):
            out[k] = np.hypot(self.xz[:, 0] - p[0], self.xz[:, 1] - p[1]).min()
        return out

    def strip(self, s0, s1, lat0, lat1, step=12.0):
        """Ring in metres along the lap from s0 to s1 between two lateral offsets, each measured
        from the road EDGE on its side (negative = left of the left edge)."""
        span = (s1 - s0) % self.length
        n = max(2, int(span / step) + 1)
        ss = [s0 + span * k / (n - 1) for k in range(n)]

        def off(s, lat):
            return self.at(s, lat + math.copysign(self.half(s), lat))

        return np.array([off(s, lat0) for s in ss] + [off(s, lat1) for s in reversed(ss)])

    def across(self, s, lat0, lat1, depth):
        """Ring of a beam across the road at s, lateral offsets from the centreline."""
        i = self.index(s)
        c, r, t = self.xz[i], self.right[i], self.tan[i] * (0.5 * depth)
        return np.array([c + r * lat0 - t, c + r * lat1 - t, c + r * lat1 + t, c + r * lat0 + t])


# ----------------------------------------------------------------------------- the map cache
def cache_elements(kind):
    files = sorted(glob.glob(str(FOLDER / "raw" / f"surroundings_{kind}_*.json")))
    if not files:
        raise SystemExit(f"no surroundings_{kind}_*.json in {FOLDER / 'raw'}")
    with open(files[0], encoding="utf-8") as f:
        return json.load(f)["elements"]


def element_ring(e):
    """Outline in (lat, lon): the way, or the longest outer ring of a relation."""
    flat = e.get("g") or max(e.get("o") or [[]], key=len)
    return np.array(flat, dtype=float).reshape(-1, 2)


def simplify(ring, tol):
    """Douglas-Peucker on a closed ring in metres."""
    ring = np.asarray(ring, dtype=float)
    if len(ring) < 5:
        return ring
    far = int(np.argmax(np.hypot(*(ring - ring[0]).T)))

    def dp(pts):
        if len(pts) < 3:
            return pts
        a, b = pts[0], pts[-1]
        ab = b - a
        n = max(float(np.hypot(*ab)), 1e-9)
        d = np.abs(ab[0] * (pts[:, 1] - a[1]) - ab[1] * (pts[:, 0] - a[0])) / n
        k = int(np.argmax(d))
        if d[k] <= tol:
            return np.array([a, b])
        return np.concatenate([dp(pts[:k + 1])[:-1], dp(pts[k:])])

    one = dp(ring[:far + 1])
    two = dp(np.concatenate([ring[far:], ring[:1]]))
    return np.concatenate([one[:-1], two[:-1]])


# ----------------------------------------------------------------------------- recipe block
def fmt_ring(lap, ring):
    lat, lon = lap.to_ll(ring[:, 0], ring[:, 1])
    return "[" + ", ".join(f"[{a:.6f}, {b:.6f}]" for a, b in zip(lat, lon)) + "]"


def add(lap, out, ring, kind, note, height=None, min_height=None):
    out.append(f"[[surroundings.add]]    # {note}")
    out.append(f"polygon = {fmt_ring(lap, np.asarray(ring, dtype=float))}")
    out.append(f'kind = "{kind}"')
    if height is not None:
        out.append(f"height = {height:.1f}")
    if min_height is not None:
        out.append(f"min_height = {min_height:.1f}")
    out.append("")


# Water of the map that is replaced: the polygons of the bay and the river reach under the
# bridges and along the walls of the lap, where the baked ground is the road, and the step
# then cuts them into 150 m squares at different levels (one of them at deck height).
WATER_POLYGONS = {9569901: "Singapore River", 9542146: "Marina Reservoir (the bay and the Kallang Basin)"}
WATER_LINES = [692147571, 692147572, 692181240, 692181242, 692181245, 692181247, 694064998, 694091088]
CORRIDOR = 125.0       # m from the centreline: the baked ground is the road's there
BORDER = 175.0         # m inside the near terrain rectangle: the ground blends to the far grid
LAWN_REACH = 230.0     # lawns of the map are taken over within this distance of the lap
LAWN_MIN_AREA = 500.0
# Paved or built over on race weekend, although the map shows a park.
NOT_LAWN = {687917300,      # Merlion Park: a granite terrace
            395120471}      # Youth Olympic Park: under the works of NS Square
GREEN = {"leisure": {"park", "garden", "pitch", "common"},
         "landuse": {"grass", "meadow", "village_green", "recreation_ground"}}


def ground_height(pts):
    """Baked terrain height (m above the finish line) at plan points, bilinear."""
    with open(FOLDER / "terrain.json", encoding="utf-8") as f:
        near = json.load(f)["near"]
    grid = np.fromfile(FOLDER / near["file"], dtype="<f4").reshape(near["nz"], near["nx"])
    pts = np.asarray(pts, dtype=float).reshape(-1, 2)
    u = np.clip((pts[:, 0] - near["x0"]) / near["step"], 0.0, near["nx"] - 1.001)
    v = np.clip((pts[:, 1] - near["z0"]) / near["step"], 0.0, near["nz"] - 1.001)
    i, j = u.astype(int), v.astype(int)
    tu, tv = u - i, v - j
    top = grid[j, i] + (grid[j, i + 1] - grid[j, i]) * tu
    bot = grid[j + 1, i] + (grid[j + 1, i + 1] - grid[j + 1, i]) * tu
    return top + (bot - top) * tv


def water_blocks(lap, out):
    """The step gives a water polygon one level, the 15th percentile of the ground under its
    outline, when the 10th and 90th percentile are within 2 m; otherwise it cuts the polygon
    into 150 m squares, each at its own level. The ground is not the water's level beside the
    lap (there it is the road) nor in the border band of the near terrain rectangle (there it
    blends into the coarse far grid). So the outlines get extra points on open ground until
    93 % of their points are there. What is left of the surface model still falls by a metre
    from the river to the Kallang Basin, so the river comes out about a metre above the bay:
    the step between them is under the east side of the Esplanade Bridge."""
    out.append("# Water: the map's polygons, simplified, cut at the near terrain rectangle, with extra points")
    out.append("# on their far shores that steer the level the step gives them (see the generator).")
    for ref in list(WATER_POLYGONS) + WATER_LINES:
        kind = "relation" if ref in WATER_POLYGONS else "way"
        out.append(f'[[surroundings.exclude]]\nosm = "{kind}/{ref}"')
    out.append("")
    far = {e["id"]: e for e in cache_elements("far") if e["t"] == "r"}
    x0, x1, z0, z1 = lap.near_rect

    def off_level(pts):
        pts = np.asarray(pts, dtype=float).reshape(-1, 2)
        edge = np.minimum(np.minimum(pts[:, 0] - x0, x1 - pts[:, 0]), np.minimum(pts[:, 1] - z0, z1 - pts[:, 1]))
        return (lap.distance(pts) < CORRIDOR) | (edge < BORDER)

    def densify(ring, usable, done):
        """Adds points on the longest edges whose ends and middle are `usable`, until
        done(off-level flags, ground heights) of the ring's points; None when it runs out of
        edges."""
        ring = [np.asarray(p, dtype=float) for p in ring]
        off = list(off_level(ring))
        g = list(ground_height(ring))
        ok = list(usable(np.array(ring)))
        for _ in range(4000):
            if done(np.array(off), np.array(g)):
                return np.array(ring)
            best, k = 0.5, -1
            for i in range(len(ring)):
                j = (i + 1) % len(ring)
                if ok[i] and ok[j]:
                    d = float(np.hypot(*(ring[j] - ring[i])))
                    if d > best:
                        best, k = d, i
            if k < 0:
                return None
            a, b = ring[k], ring[(k + 1) % len(ring)]
            # A hair off the edge, so that the point is not dropped as collinear.
            q = 0.5 * (a + b) + (b - a)[::-1] * np.array([1.0, -1.0]) / best * 0.05
            ring.insert(k + 1, q)
            off.insert(k + 1, bool(off_level(q)[0]))
            g.insert(k + 1, float(ground_height(q)[0]))
            ok.insert(k + 1, bool(usable(q[None])[0]))
        return None

    for ref, name in WATER_POLYGONS.items():
        ll = element_ring(far[ref])
        x, z = lap.to_xz(ll[:, 0], ll[:, 1])
        whole = simplify(np.stack([x, z], axis=1), 10.0)
        ring = whole
        for a, b, c in ((1.0, 0.0, -x0), (-1.0, 0.0, x1), (0.0, 1.0, -z0), (0.0, -1.0, z1)):
            ring = sg.clip_halfplane(ring, a, b, c)
        ring = densify(ring, lambda p: ~off_level(p), lambda off, g: off.mean() <= 0.07)
        if ring is None:
            raise SystemExit(f"{name}: not enough shore on open ground to level the water on")
        level = float(np.percentile(ground_height(ring), 15))
        add(lap, out, ring, "water", f"{name}: {len(ring)} points, comes out at {level:+.2f} m")
        for label, (a, b, c) in (("west", (-1.0, 0.0, x0 - 1.0)), ("east", (1.0, 0.0, -x1 - 1.0)),
                                 ("north", (0.0, -1.0, z0 - 1.0)), ("south", (0.0, 1.0, -z1 - 1.0))):
            piece = sg.clip_halfplane(whole, a, b, c)
            if len(piece) >= 3 and abs(sg.signed_area(piece)) > 400.0:
                add(lap, out, piece, "water", f"{name}, {label} of the detailed ground")


def lawn_blocks(lap, out):
    out.append("# Lawns. The land-cover class \"grass\" is what the map says nothing about, which here is")
    out.append("# paving (environment.json paints it grey); the real lawns of the map near the lap are")
    out.append("# repeated as \"farmland\", which environment.json paints as mown grass.")
    rows = []
    for e in cache_elements("near"):
        t = e.get("tags", {})
        if e["t"] == "n" or e["id"] in NOT_LAWN or "building" in t:
            continue
        if not any(t.get(k) in v for k, v in GREEN.items()):
            continue
        ll = element_ring(e)
        if len(ll) < 4:
            continue
        x, z = lap.to_xz(ll[:, 0], ll[:, 1])
        ring = np.stack([x, z], axis=1)
        if lap.distance(ring).min() > LAWN_REACH or abs(sg.signed_area(ring)) < LAWN_MIN_AREA:
            continue
        ring = simplify(ring, 1.5)
        name = t.get("name") or t.get("leisure") or t.get("landuse")
        ref = f"{'relation' if e['t'] == 'r' else 'way'} {e['id']}"
        rows.append((lap.locate(*ring.mean(axis=0))[0], ref, name, ring))
    for s, ref, name, ring in sorted(rows, key=lambda r: (-abs(sg.signed_area(r[3])))):
        add(lap, out, ring, "farmland", f"{name} ({ref}), near s = {s:.0f}")


