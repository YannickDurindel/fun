def pit_building():
    """F1 Pit Building, 1 Republic Boulevard: 350 m long, three storeys (grandprix.com, 1 Sept
    2007; rental kit of the building, 2025), garages on the ground floor, glass fronts above
    with jade-green bands and barrel roofs, the race-control tower on stilts at the Turn 19 end
    (Commons: "Singapore (SG), Marina Bay Street Circuit, F1 Pit Building -- 2019 -- 4478",
    "Preparations for the 2023 Singapore Grand Prix - BugWarp 12 / 13"). Depth 34 m and the
    storey heights are read off those photographs. The track is on its +x side."""
    m = new_mesh()
    m.anchor(0.0, 0.0)
    grey, light, jade, glass = lin(PIT_GREY), lin(PIT_LIGHT), lin(JADE), lin(GLASS, 1.0)
    half, x0, x1 = 175.0, -17.0, 17.0
    sg.box(m, "building_wall", (x0, -1.5, -half), (x1, 5.2, half), grey)
    # Garage fronts: 36 doors seen as one dark, lit band.
    m.face("building_glass", [[x1 + 0.05, 0.3, -half + 6], [x1 + 0.05, 0.3, half - 6], [x1 + 0.05, 4.4, half - 6],
                              [x1 + 0.05, 4.4, -half + 6]], [1.0, 0.0, 0.0], glass)
    bays = 7
    span = 2.0 * half / bays
    for k in range(bays):
        z0, z1 = -half + k * span + 2.0, -half + (k + 1) * span - 2.0
        sg.box(m, "building_wall", (x0, 5.2, z0), (x1 + 1.5, 13.0, z1), light)
        for x, nx in ((x1 + 1.55, 1.0), (x0 - 0.05, -1.0)):
            m.face("building_glass", [[x, 5.6, z0 + 1], [x, 5.6, z1 - 1], [x, 12.2, z1 - 1], [x, 12.2, z0 + 1]],
                   [nx, 0.0, 0.0], glass)
        for y in (8.6, 12.3):   # the jade bands across the glass
            sg.box(m, "building_roof", (x1 + 1.5, y, z0), (x1 + 2.0, y + 0.7, z1), jade)
        barrel(m, "building_roof", x0 - 0.5, x1 + 2.0, z0, z1, 13.0, 3.6, jade)
    # The lettered fascia over the middle bays.
    sg.box(m, "building_wall", (x1 + 2.0, 9.6, -80.0), (x1 + 2.3, 11.4, 80.0), light)
    # Race control: a glass box on stilts beyond the south end, under its own scoop of a roof.
    z0, z1 = half + 6.0, half + 40.0
    for x in (x0 + 2.0, x1 + 4.0):
        for z in (z0 + 2.0, 0.5 * (z0 + z1), z1 - 2.0):
            beam(m, "metal", [x, -1.0, z], [x, 9.0, z], 0.7, light)
    sg.box(m, "building_glass", (x0, 9.0, z0), (x1 + 6.0, 14.5, z1), glass)
    sg.box(m, "metal", (x0 - 1.0, 8.5, z0 - 1.0), (x1 + 8.0, 9.0, z1 + 1.0), light)
    barrel(m, "building_roof", x0 - 2.0, x1 + 8.0, z0 - 1.0, z1 + 1.0, 14.5, 4.2, jade)
    sg.box(m, "building_wall", (x0, -1.5, half), (x0 + 8.0, 9.0, half + 6.0), grey)     # lift and stair core
    return m


def flyer():
    """Singapore Flyer: 165 m high, wheel 150 m across, 28 capsules of 7 x 4 m (Wikipedia,
    "Singapore Flyer"). A ladder-truss rim on cable spokes, carried by two legs on each side
    of the hub. The wheel is in the local x-y plane."""
    m = new_mesh()
    m.anchor(0.0, 0.0)
    white, lit = lin(STEEL_WHITE), lin((0.85, 0.92, 1.0))
    hub = np.array([0.0, 90.0, 0.0])
    r, n = 75.0, 28
    ang = np.arange(n) * (2.0 * np.pi / n)
    for side in (-1.3, 1.3):
        ring = [hub + np.array([r * math.cos(a), r * math.sin(a), side]) for a in ang]
        for k in range(n):
            beam(m, "metal", ring[k], ring[(k + 1) % n], 0.9, white)
    for k, a in enumerate(ang):
        d = np.array([math.cos(a), math.sin(a), 0.0])
        beam(m, "metal", hub + d * 3.0, hub + d * (r - 0.4), 0.22, white)                  # spoke
        c = hub + d * (r + 3.4)
        sg.box(m, "emissive_window", (c[0] - 3.5, c[1] - 1.6, -2.0), (c[0] + 3.5, c[1] + 1.6, 2.0), lit)
    beam(m, "metal", hub + [0.0, 0.0, -9.0], hub + [0.0, 0.0, 9.0], 5.0, white)            # spindle
    for z in (-9.0, 9.0):
        for x in (-22.0, 22.0):
            beam(m, "metal", hub + [0.0, 0.0, z], [x, 8.0, z * 2.6], 2.6, white)
    return m


def anderson_bridge(lap, s_mid, span):
    """Anderson Bridge (1910): 70 m long, 28 m wide, three steel bowstring trusses with ribs
    across them and a rusticated stone arch at each end (Wikipedia, "Anderson Bridge"). The
    lap uses the bay between the left and the middle truss; the other bay is paved for
    pedestrians (Commons: "Preparations for the 2023 Singapore Grand Prix - BugWarp 21 / 22 /
    23"). Truss height 7 m above the deck: read off those photographs. The trusses follow the
    hump of the road."""
    m = new_mesh()
    m.anchor(0.0, 0.0)
    steel, stone = lin(STEEL_WHITE), lin(STONE)
    half = 0.5 * span
    lines = (-6.9, 6.9, 20.7)       # the wall and fence of the lap stand inside the first two
    panels = 12
    zs = np.linspace(-half, half, panels + 1)
    y0 = lap.height(s_mid)

    def deck(z):
        return lap.height(s_mid - z) - y0

    def top(z):
        return deck(z) + 1.3 + 6.9 * (1.0 - (z / half) ** 2)

    for x in lines:
        for k in range(panels):
            a, b = zs[k], zs[k + 1]
            beam(m, "metal", [x, top(a), a], [x, top(b), b], 0.55, steel)                 # arch
            # Plate girder at parapet height.
            m_lo = min(deck(a), deck(b)) - 1.2
            for nx in (-1.0, 1.0):
                m.face("metal", [[x + nx * 0.25, m_lo, a], [x + nx * 0.25, m_lo, b], [x + nx * 0.25, deck(b) + 1.3, b],
                                 [x + nx * 0.25, deck(a) + 1.3, a]], [nx, 0.0, 0.0], steel)
            if 0 < k:
                beam(m, "metal", [x, deck(a) + 1.3, a], [x, top(a), a], 0.3, steel)        # hanger
            if 0 < k < panels - 1:
                lo, hi = (a, b) if k % 2 else (b, a)
                beam(m, "metal", [x, deck(lo) + 1.3, lo], [x, top(hi), hi], 0.22, steel)   # diagonal
    # Ribs over both bays where the arch is high enough to drive under.
    for z in zs[3:-3]:
        for xa, xb in zip(lines[:-1], lines[1:]):
            xm = 0.5 * (xa + xb)
            beam(m, "metal", [xa, top(z), z], [xm, top(z) + 0.9, z], 0.3, steel)
            beam(m, "metal", [xm, top(z) + 0.9, z], [xb, top(z), z], 0.3, steel)
    for z in (-half - 2.0, half + 2.0):
        for x in lines:
            sg.box(m, "concrete", (x - 1.3, deck(z) - 2.0, z - 1.6), (x + 1.3, deck(z) + 6.0, z + 1.6), stone)
    return m


def shell(a, b, h, colour, rings=5, sides=16):
    """One of the two shells of Esplanade - Theatres on the Bay: a low dome of glass under
    pointed aluminium sunshades (the "durian"). Half-axes a (along x) and b, height h; the
    facets stand in for the spikes."""
    m = new_mesh()
    m.anchor(0.0, 0.0)
    col = lin(colour)
    pts = []
    for i in range(rings + 1):
        phi = 0.5 * np.pi * i / rings
        # Odd rings are turned by half a facet: triangles instead of quads, a spikier skin.
        off = 0.5 if i % 2 else 0.0
        ring = []
        for j in range(sides):
            th = 2.0 * np.pi * (j + off) / sides
            bump = 1.0 + (0.035 if (i + j) % 2 else -0.02)
            ring.append(np.array([a * math.cos(phi) * math.cos(th) * bump, h * math.sin(phi) * bump - 0.5,
                                  b * math.cos(phi) * math.sin(th) * bump]))
        pts.append(ring)
    inside = np.array([0.0, 0.0, 0.0])
    for i in range(rings):
        for j in range(sides):
            j1 = (j + 1) % sides
            p, q = pts[i], pts[i + 1]
            if i == rings - 1:
                m.face("metal", [p[j], p[j1], q[0]], None, col, away_from=inside)
                continue
            if i % 2 == 0:
                m.face("metal", [p[j], p[j1], q[j]], None, col, away_from=inside)
                m.face("metal", [p[j1], q[j1], q[j]], None, col, away_from=inside)
            else:
                m.face("metal", [p[j], q[j1], q[j]], None, col, away_from=inside)
                m.face("metal", [p[j], p[j1], q[j1]], None, col, away_from=inside)
    return m


def write_models(lap):
    (FOLDER / "landmarks").mkdir(exist_ok=True)
    marks = []
    near = {e["id"]: e for e in cache_elements("near") if e["t"] != "n"}

    # Pit building: where the map has it, parallel to the pit straight.
    ll = element_ring(near[49890775])
    x, z = lap.to_xz(ll[:, 0], ll[:, 1])
    s, lat = lap.locate(float(x.mean()), float(z.mean()))
    # The map's outline includes the paddock canopies: the front stands 17 m from the middle
    # of the road (pit wall and a pit lane of three lanes), the model is 34 m deep, so its
    # middle (the model origin) is 34 m from the centreline.
    write(pit_building(), "pit_building")
    marks.append({"model": "pit_building", "at": {"s": round(s % lap.length, 1), "side": -1, "dist": 34.0}})

    ids, pts = flyer_parts()
    if len(pts) < 10:
        raise SystemExit("the capsules of the Singapore Flyer were not found in the map cache")
    x, z = lap.to_xz(pts[:, 0], pts[:, 1])
    xz = np.stack([x, z], axis=1)
    hub = xz.mean(axis=0)
    # Direction of the wheel plane: the principal axis of the capsule columns.
    _, _, vt = np.linalg.svd(xz - hub)
    d = vt[0]
    lat_h, lon_h = lap.to_ll(hub[0], hub[1])
    write(flyer(), "flyer")
    # yaw turns the model's -z to (-sin, -cos); its x axis (the wheel plane) to (cos, -sin).
    marks.append({"model": "flyer", "at": {"latlon": [round(float(lat_h), 6), round(float(lon_h), 6)]},
                  "yaw_deg": round(math.degrees(math.atan2(-d[1], d[0])), 1), "y_offset": 0.3})

    ll = element_ring(near[29377119])       # Fullerton Road on the bridge
    x, z = lap.to_xz(ll[:, 0], ll[:, 1])
    ends = sorted(lap.locate(float(a), float(b))[0] for a, b in zip(x, z))
    s_mid, span = 0.5 * (ends[0] + ends[-1]), ends[-1] - ends[0]
    write(anderson_bridge(lap, s_mid, span), "anderson_bridge")
    marks.append({"model": "anderson_bridge", "at": {"s": round(s_mid, 1), "side": 1, "dist": 0.0}})

    # Esplanade: the two shells, on the footprints of the map (their long axes from them).
    for ref, name, height in ((256163011, "esplanade_concert_hall", 30.0), (256163012, "esplanade_theatre", 33.0)):
        ll = element_ring(near[ref])
        x, z = lap.to_xz(ll[:, 0], ll[:, 1])
        xz = np.stack([x, z], axis=1)
        c = 0.5 * (xz.min(axis=0) + xz.max(axis=0))
        _, _, vt = np.linalg.svd(xz - xz.mean(axis=0))
        along = (xz - c) @ vt[0]
        cross = (xz - c) @ vt[1]
        write(shell(0.5 * float(np.ptp(along)), 0.5 * float(np.ptp(cross)), height, DURIAN), name)
        lat_c, lon_c = lap.to_ll(c[0], c[1])
        marks.append({"model": name, "at": {"latlon": [round(float(lat_c), 6), round(float(lon_c), 6)]},
                      "yaw_deg": round(math.degrees(math.atan2(-vt[0][1], vt[0][0])), 1)})

    with open(FOLDER / "landmarks.json", "w", encoding="utf-8") as f:
        f.write("[\n" + ",\n".join(" " + json.dumps(e) for e in marks) + "\n]\n")
    print(f"{FOLDER / 'landmarks.json'}: {len(marks)} landmarks")


