# Road bridges of the map. The step builds every bridge=* way as a deck on a straight grade and
# lifts it to 6.5 m where it crosses the lap. That is wrong twice here: the lap's own roads on
# the Anderson and Esplanade Bridges are such ways (a deck 6.5 m over the road), and the
# Benjamin Sheares Bridge (the East Coast Parkway viaduct, which the lap passes under four
# times) is far higher. Every bridge way that comes within BRIDGE_REACH of the centreline is
# left out; the viaduct and its slip roads are rebuilt as decks on piers at their real height.
BRIDGE_REACH = 45.0
# Deck height above the level of the finish line, by road class. The Benjamin Sheares Bridge
# is 29 m above the water at its main span (Wikipedia, "Benjamin Sheares Bridge"); where the
# lap passes under its approach spans the deck is about 15 m up (Commons: "Marina Bay Street
# Circuit near Singapore Flyer 11Jul2026 02", "Preparations for the 2023 Singapore Grand Prix -
# BugWarp 01"): estimate from the fence posts (2.5 m) in those photographs.
VIADUCT = {"motorway": 16.5, "motorway_link": 14.0, "trunk_link": 14.0}
DECK_DEPTH = 1.8
PIER_SPACING = 55.0


def bridge_blocks(lap, out):
    out.append("# Bridges of the map that cross or follow the lap (see the generator): left out, and the")
    out.append("# Benjamin Sheares Bridge rebuilt at its height, on piers.")
    drop, decks = [], []
    for e in cache_elements("near"):
        t = e.get("tags", {})
        if e["t"] != "w" or t.get("bridge") in (None, "no") or "highway" not in t or "g" not in e:
            continue
        ll = element_ring(e)
        x, z = lap.to_xz(ll[:, 0], ll[:, 1])
        line = np.stack([x, z], axis=1)
        # Resampled, so that a long straight way is tested along its whole length.
        seg = np.hypot(*np.diff(line, axis=0).T)
        d = np.concatenate([[0.0], np.cumsum(seg)])
        if d[-1] < 1.0:
            continue
        u = np.linspace(0.0, d[-1], max(2, int(d[-1] / 6.0) + 1))
        fine = np.stack([np.interp(u, d, line[:, 0]), np.interp(u, d, line[:, 1])], axis=1)
        if lap.distance(fine).min() > BRIDGE_REACH:
            continue
        drop.append(e["id"])
        # Only the parkway and its ramps: Esplanade Drive's bridges are the level road beside the lap.
        if t["highway"] in VIADUCT and t.get("layer") != "-1" and (t["highway"].startswith("motorway") or "East Coast" in t.get("name", "")):
            lanes = float(t.get("lanes", "2"))
            decks.append((e["id"], t.get("name", t["highway"]), VIADUCT[t["highway"]], lanes * 3.7 + 3.0, fine))
    for ref in sorted(drop):
        out.append(f'[[surroundings.exclude]]\nosm = "way/{ref}"')
    out.append("")
    for ref, name, top, width, fine in decks:
        tan = np.gradient(fine, axis=0)
        tan /= np.maximum(np.hypot(*tan.T), 1e-9)[:, None]
        right = np.stack([-tan[:, 1], tan[:, 0]], axis=1)
        cut = list(range(0, len(fine) - 1, 14)) + [len(fine) - 1]
        for a, b in zip(cut[:-1], cut[1:]):
            sl = slice(a, b + 1)
            ring = np.concatenate([fine[sl] - right[sl] * (0.5 * width), (fine[sl] + right[sl] * (0.5 * width))[::-1]])
            low = float(ground_height(ring).min())      # the step measures heights from here
            add(lap, out, ring, "concrete", f"{name} (way {ref}), deck {top:.1f} m above the finish line",
                height=top - low, min_height=top - DECK_DEPTH - low)
        for k in range(int(PIER_SPACING / 12.0), len(fine) - 2, int(PIER_SPACING / 6.0)):
            c, r, t = fine[k], right[k] * (0.3 * width), tan[k] * 1.3
            ring = np.array([c - r - t, c + r - t, c + r + t, c - r + t])
            if lap.distance(ring).min() < 12.0:
                continue        # no pier on the road or in its walls
            low = float(ground_height(ring).min())
            add(lap, out, ring, "concrete", "pier", height=top - DECK_DEPTH - low + 0.1)


def flyer_parts():
    """The Singapore Flyer of the map: one building:part column per capsule. Returns their ids,
    the hub in lat / lon and the unit direction of the wheel plane in (east, south)."""
    ids, pts = [], []
    for e in cache_elements("far"):
        t = e.get("tags", {})
        if e["t"] != "w" or "building" not in t and "building:part" not in t:
            continue
        ll = element_ring(e)
        try:
            h = float(t.get("height", "0"))
        except ValueError:
            continue
        c = ll.mean(axis=0)
        if 100.0 <= h <= 170.0 and abs(c[0] - 1.28930) < 0.0012 and abs(c[1] - 103.86310) < 0.0012 and len(ll) <= 8:
            ids.append(e["id"])
            pts.append(c)
    return ids, np.array(pts)


def recipe_block(lap):
    out = [BEGIN, ""]
    water_blocks(lap, out)
    lawn_blocks(lap, out)
    trackside_blocks(lap, out)
    bridge_blocks(lap, out)
    ids, _ = flyer_parts()
    out.append("# Replaced by models (landmarks.json): the pit building, the capsules of the Singapore")
    out.append("# Flyer (the map has one 150 m column per capsule) and the two shells of the Esplanade.")
    for ref in [49890775, 256163011, 256163012, 393090492] + sorted(ids):
        out.append(f'[[surroundings.exclude]]\nosm = "way/{ref}"')
    out += ["", END]
    return "\n".join(out) + "\n"


def write_recipe(lap):
    text = RECIPE.read_text(encoding="utf-8")
    block = recipe_block(lap)
    if BEGIN in text:
        text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n", lambda m: block, text, flags=re.S)
    else:
        text = text.rstrip("\n") + "\n\n" + block
    RECIPE.write_text(text, encoding="utf-8")
    print(f"{RECIPE}: generated block of {block.count(chr(10))} lines")


# ----------------------------------------------------------------------------- mesh helpers
def new_mesh():
    return sg.SceneryMesh(-1.0e6, -1.0e6, 4.0e6)       # one chunk: one node per model


def beam(mesh, material, a, b, w, colour):
    """Square bar of side w from point a to point b."""
    a, b = np.asarray(a, dtype=float), np.asarray(b, dtype=float)
    d = b - a
    n = float(np.linalg.norm(d))
    if n < 1e-6:
        return
    d /= n
    ref = np.array([0.0, 1.0, 0.0]) if abs(d[1]) < 0.9 else np.array([1.0, 0.0, 0.0])
    u = np.cross(d, ref)
    u /= np.linalg.norm(u)
    v = np.cross(d, u)
    h = 0.5 * w
    mid = 0.5 * (a + b)
    for p, q in ((u, v), (v, -u), (-u, -v), (-v, u)):
        mesh.face(material, [a + p * h + q * h, a + p * h - q * h, b + p * h - q * h, b + p * h + q * h], None, colour,
                  away_from=mid)


def barrel(mesh, material, x0, x1, z0, z1, y_eave, rise, colour, n=6):
    """Barrel vault over the rectangle, its axis along z, plus the two gable ends."""
    xs = np.linspace(x0, x1, n + 1)
    t = (xs - x0) / (x1 - x0)
    ys = y_eave + rise * np.sin(np.pi * t)
    c = np.array([0.5 * (x0 + x1), y_eave - 5.0, 0.5 * (z0 + z1)])
    for k in range(n):
        mesh.face(material, [[xs[k], ys[k], z0], [xs[k + 1], ys[k + 1], z0], [xs[k + 1], ys[k + 1], z1], [xs[k], ys[k], z1]],
                  None, colour, away_from=c)
    for z in (z0, z1):
        mesh.face(material, [[x, y, z] for x, y in zip(xs, ys)], None, colour, away_from=c)


def write(mesh, name):
    stats = sg.write_glb(FOLDER / "landmarks" / f"{name}.glb", mesh, f"{TRACK_ID}_{name}", GENERATOR)
    print(f"  {name}.glb: {stats['triangles']} triangles, {stats['bytes'] / 1000:.0f} kB")
    return stats


